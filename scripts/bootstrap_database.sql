-- 7. ENABLE RLS (Row Level Security) ON EVERYTHING
-- ============================================================================
-- We use a simplified RLS model: "Authenticated users can see everything in their restaurant"
-- For a real multi-tenant app, you'd check profile.restaurant_id vs row.restaurant_id
-- For now, we allow ALL authenticated users full access (assuming backend/middleware handles tenant selection via app.current_restaurant_id)

-- Helper to enable RLS quickly
DO $$ 
DECLARE 
    t text;
BEGIN 
    FOR t IN 
        SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' 
    LOOP 
        EXECUTE 'ALTER TABLE ' || t || ' ENABLE ROW LEVEL SECURITY';
        EXECUTE 'DROP POLICY IF EXISTS "Access own restaurant" ON ' || t;
        -- Simple permissive policy for now (refine later if needed)
        EXECUTE 'CREATE POLICY "Access own restaurant" ON ' || t || ' FOR ALL USING (true) WITH CHECK (true)';
    END LOOP; 
END $$;

